// The app's system layer: thin calls into the Rust core (src-tauri/src/lib.rs).
import { invoke } from '@tauri-apps/api/core';

/** @returns {Promise<import('./system-contracts').SystemAdapter>} */
export async function createTauriSys() {
  const info = /** @type {import('./system-contracts').NativeSystemInfo} */ (await invoke('sys_info'));
  return {
    openDialog: (options) => import('@tauri-apps/plugin-dialog').then(({ open }) => open(options)),
    saveDialog: (options) => import('@tauri-apps/plugin-dialog').then(({ save }) => save(options)),
    queryOperation: (request) => invoke('query_operation', { request }),
    selectResource: (selection) => invoke('select_resource', { selection }),
    prepareOperation: (request) => invoke('prepare_operation', { request }),
    executeOperation: (planId) => invoke('execute_operation', { planId }),
    recoverOperation: (request) => invoke('recover_operation', { request }),
    cancelOperation: (planId) => invoke('cancel_operation', { planId }),
    info: { version: __APP_VERSION__, pid: info.pid, env: info.env, home: info.home, dataDir: info.data_dir, exe: info.exe, portable: info.portable, args: info.args, launch: info.launch || [], cpu: info.cpu || '', ramBytes: info.ram_bytes || 0, osName: info.os_name || '', osVersion: info.os_version || '', osBuild: info.os_build || 0 },
    runPS: (script, input, timeoutMs = 60000) => invoke('run_ps', { script, input: input ?? null, timeoutMs }),
    copyFile: (source, target) => invoke('copy_file_checked', { source, target }),
    observeTransferTarget: (target) => invoke('observe_transfer_target', { target }),
    acquireTransferUndo: (id) => invoke('acquire_transfer_undo', { id }),
    reserveTransferRestore: () => invoke('reserve_transfer_restore'),
    releaseTransferUndo: (token) => invoke('release_transfer_undo', { token }),
    pinTransferRegistryExport: (token, name) => invoke('pin_transfer_registry_export', { token, name }),
    importTransferRegistryExport: (token, pin) => invoke('import_transfer_registry_export', { token, pin }),
    stageTransferUndo: (token, id, step, target, expected, apply) => invoke('stage_transfer_undo', { token, id, step, target, expected, apply }),
    savedTransferUndoStage: (token, id, step, target, expected) => invoke('saved_transfer_undo_stage', { token, id, step, target, expected }),
    transferOriginalAtTarget: (target, receipt) => invoke('transfer_original_at_target', { target, receipt }),
    captureTransferReplacement: (target, directory) => invoke('capture_transfer_replacement', { target, directory }),
    validateTransferReplacement: (target, receipt) => invoke('validate_transfer_replacement', { target, receipt }),
    restoreTransferReplacement: (target, receipt) => invoke('restore_transfer_replacement', { target, receipt }),
    secretGet: () => invoke('secret_get'),
    secretKeys: () => invoke('secret_keys'),
    secretSet: (value) => invoke('secret_set', { value }),
    prepareProcess: (request) => invoke('prepare_process_operation', { request }),
    executeProcess: (planId) => invoke('execute_process_operation', { planId }),
    elevateHandoff: () => invoke('elevate_handoff'),
    bootState: () => invoke('boot_state'),
    taskInventory: (cursor = null) => invoke('task_inventory', { cursor }),
    taskOwnedStatus: (role) => invoke('task_owned_status', { role }),
    selectTaskProgram: () => invoke('select_task_program'),
    prepareTask: (request) => invoke('prepare_task_operation', { request }),
    executeTask: (planId) => invoke('execute_task_operation', { planId }),
    taskRecovery: (journalId) => invoke('task_recovery', { journalId }),
    driverInventory: () => invoke('driver_inventory'),
    prepareDriver: (request) => invoke('prepare_driver_operation', { request }),
    executeDriver: (planId) => invoke('execute_driver_operation', { planId }),
    driverRecovery: (journalId) => invoke('driver_recovery', { journalId }),
    prepareBoot: (request) => invoke('prepare_boot_operation', { request }),
    executeBoot: (planId) => invoke('execute_boot_operation', { planId }),
    debloatStatus: () => invoke('debloat_status'),
    prepareDebloat: (request) => invoke('prepare_debloat_operation', { request }),
    prepareDebloatRecovery: (request) => invoke('prepare_debloat_recovery', { request }),
    executeDebloat: (planId) => invoke('execute_debloat_operation', { planId }),
    exec: (file, args) => invoke('exec', { file, args }),
    runCommandLine: (commandLine) => invoke('run_command_line', { commandLine }),
    launch: (file, args = []) => invoke('launch', { file, args }),
    reserveUpdateDownload: (expected) => invoke('reserve_update_download', { expected }),
    cancelUpdateDownload: (id) => invoke('cancel_update_download', { id }),
    launchVerifiedUpdate: (id) => invoke('launch_verified_update', { id }),
    readDir: (path) => invoke('read_dir', { path }),
    stat: (path) => invoke('stat', { path }),
    exists: (path) => invoke('exists', { path }),
    readText: (path) => invoke('read_text', { path }),
    readOptionalText: (path) => invoke('read_optional_text', { path }),
    restorePoints: () => invoke('list_restore_points'),
    prepareRestoreRemoval: (request) => invoke('prepare_restore_removal', { request }),
    executeRestoreRemoval: (planId) => invoke('execute_restore_removal', { planId }),
    writeText: (path, contents) => invoke('write_text', { path, contents }),
    writeTextAtomic: (path, contents) => invoke('write_text_atomic', { path, contents }),
    commitStagedFile: (source, target) => invoke('commit_staged_file', { source, target }),
    makeDir: (path) => invoke('make_dir', { path }),
    removePath: (path) => invoke('remove_path', { path }),
    trash: (path) => invoke('move_to_trash', { path }),
    walk: (roots, maxDirDepth, maxFileDepth) => invoke('walk', { roots, maxDirDepth, maxFileDepth }),
    folderSize: (path, maxEntries, maxMs) => invoke('folder_size', { path, maxEntries, maxMs }),
    takeSnapshot: (out, name, fileRoots, fileDepth, regRoots, excludes) => invoke('take_snapshot', { out, name, fileRoots, fileDepth, regRoots, excludes }),
    compareSnapshots: (before, after, limit) => invoke('compare_snapshots', { before, after, limit }),
    cancelSnapshot: () => invoke('cancel_snapshot'),
    secureErase: (path, passes) => invoke('secure_erase_file', { path, passes }),
    cancelErase: () => invoke('cancel_erase'),
    beginScans: () => invoke('begin_scans'),
    cancelScans: () => invoke('cancel_scans'),
    snapshotSubtree: (path, key) => invoke('snapshot_subtree', { path, key }),
    trashMany: (paths) => invoke('move_many_to_trash', { paths }),
    listJunk: (root, maxMs) => invoke('list_junk', { root, maxMs }),
    print: (text) => invoke('cli_print', { text }),
    trackStart: () => invoke('track_start'),
    trackLaunch: (file) => invoke('track_launch', { file }),
    trackRunning: () => invoke('track_running'),
    trackPeek: () => invoke('track_peek'),
    trackStop: () => invoke('track_stop'),
    waitProcess: (pid, timeoutMs) => invoke('wait_process', { pid, timeoutMs }),
    sha256Files: (paths) => invoke('sha256_files', { paths }),
    appendText: (path, contents) => invoke('append_text', { path, contents }),
    uninstallKeyTimes: () => invoke('uninstall_key_times'),
    setTray: ({ close, minimize, visible }) => invoke('set_tray', { close: String(close || 'ask'), minimize: !!minimize, visible: !!visible }),
    hideToTray: () => invoke('hide_to_tray'),
    closeAnswered: () => invoke('close_answered'),
    frontendReady: () => invoke('frontend_ready'),
    setOnTop: (on) => invoke('set_on_top', { on }),
    showWindow: () => invoke('show_window'),
    listProcesses: () => invoke('list_processes'),
    exeArch: (paths) => invoke('exe_arch', { paths }),
    searchRegistry: (term, max, maxMs) => invoke('search_registry', { term, max, maxMs }),
    quit: (code = 0) => invoke('quit', { code }),
  };
}
